import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { WorkspaceTabs } from '../src/components/WorkspaceTabs';
import { WorkspaceNotePage } from '../src/components/WorkspaceNotePage';
import { Sidebar } from '../src/components/Sidebar';
import { TasksPage } from '../src/components/TasksPage';
import { GradesPage } from '../src/components/GradesPage';
const noop = () => {};
const navigation = renderToStaticMarkup(<Sidebar section="courses" pageActive profileName="Élève" onSectionChange={noop} />);
assert.match(navigation, /aria-current="page"/);
for (const label of ['Accueil','Planning','Cours','Évaluations','À faire','Formations','Réglages','Mes notes']) assert.ok(navigation.includes(label), label);
assert.ok(!navigation.includes('Assistant'), 'AI access belongs to the right edge tab');
assert.ok(!navigation.includes('status-dot'), 'No invented online indicator');
assert.ok(!navigation.includes('profil local'), 'Cloud profile must not be described as local-only');
const emptyTasks = renderToStaticMarkup(<TasksPage tasks={[]} subjects={[]} onToggle={noop} onAdd={noop} onEdit={noop} onDelete={noop} />);
assert.ok(emptyTasks.includes('Ta liste est prête'));
assert.ok(emptyTasks.includes('Ajouter une tâche'));
assert.ok(emptyTasks.includes('type="search"'));
const completedTasks = renderToStaticMarkup(<TasksPage tasks={[{id:'done',title:'Task unique',dueAt:'2026-10-07T18:00:00Z',completed:true,priority:'medium'}]} subjects={[]} onToggle={noop} onAdd={noop} onEdit={noop} onDelete={noop} />);
assert.ok(completedTasks.includes('Toutes tes tâches sont terminées'));
assert.ok(!completedTasks.includes('Task unique'));
const grades = renderToStaticMarkup(<GradesPage assessments={[]} subjects={[]} onAddAssessment={noop} onEditAssessment={noop} onDeleteAssessment={noop} onOpenPdf={noop} onOpenConversation={noop} />);
assert.ok(!grades.includes('Validée'), 'No institutional approval inferred from a computed grade');
console.log('UI markup regressions: navigation, truthful states, empty and completed tasks, grading passed. Browser interaction remains a separate check.');

const tabs = renderToStaticMarkup(<WorkspaceTabs section="drawing" documents={[]} openDocumentIds={[]} activeDocumentId={null} onActivatePage={noop} onActivateNote={noop} onCloseNote={noop} onCreateNote={noop} />);
assert.ok(tabs.includes('id="workspace-tab-page"'));
assert.ok(tabs.includes('aria-controls="workspace-panel-page"'));
assert.ok(tabs.includes('Notes'));
assert.ok(!navigation.includes('Dessins et photos'), 'Drawings belong to notes, no separate application');
const note = renderToStaticMarkup(<WorkspaceNotePage note={{id:'test',title:'Note test',markdown:'Texte',tags:[],subjectIds:[],createdAt:'2026-10-08T10:00:00Z',updatedAt:'2026-10-08T10:00:00Z'}} subjects={[]} storageKey="test-notes" onUpdateNote={noop} onOpenSubjects={noop} onDeleteNote={noop} />);
assert.ok(note.includes('Sauvegarde automatique activée'));
assert.ok(!note.includes('Enregistrée automatiquement'), 'Never claim a save receipt before persistence success');
console.log('Redesign regressions: direct notes/drawing navigation, tab association, honest initial save status passed.');
